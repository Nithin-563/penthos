"""Local HTTP wrapper for Pari.

Serves the model that this machine already has loaded — it never calls another
AI service. The wire format is OpenAI-compatible only so existing clients and
UIs can point at `http://127.0.0.1:8080/v1` without a custom SDK; every byte is
generated by Pari on your own hardware.

Endpoints
    GET  /health
    GET  /v1/models
    POST /v1/chat/completions      (stream: true | false)

Usage
    python inference/server.py --host 127.0.0.1 --port 8080
    python inference/server.py --host 0.0.0.0 --api-key "$PARI_API_KEY"

Defaults to loopback on purpose: binding a model server to the public internet
is a decision you make with a key and a tunnel, not a default.
"""

from __future__ import annotations

import argparse
import hmac
import json
import os
import sys
import time
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any, Iterator

# Allow `python inference/server.py` to import the repo packages.
REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from inference.prompt import (  # noqa: E402
    ENABLE_THINKING,
    MAX_TOKENS,
    MODEL,
    MODEL_DISPLAY,
    PARI_SYSTEM_PROMPT,
    TEMP,
    TOP_P,
)

DEFAULT_MODEL_ID = "pari"
MAX_REQUEST_BYTES = 8 * 1024 * 1024
MAX_MAX_TOKENS = 16384


class RequestError(ValueError):
    """A client request that cannot be served."""


# ---------------------------------------------------------------------------
# Request / response helpers (pure, testable without a model)
# ---------------------------------------------------------------------------

def parse_chat_request(payload: Any, default_model: str = DEFAULT_MODEL_ID) -> dict:
    """Validate an OpenAI-style chat request and fill in Pari's defaults."""
    if not isinstance(payload, dict):
        raise RequestError("request body must be a JSON object")

    raw_messages = payload.get("messages")
    if not isinstance(raw_messages, list) or not raw_messages:
        raise RequestError("messages must be a non-empty list")

    messages: list[dict[str, str]] = []
    for index, item in enumerate(raw_messages):
        if not isinstance(item, dict):
            raise RequestError(f"messages[{index}] must be an object")
        role = item.get("role")
        content = item.get("content")
        if role not in ("system", "developer", "user", "assistant"):
            raise RequestError(
                f"messages[{index}].role must be system, user, or assistant"
            )
        if not isinstance(content, str):
            raise RequestError(f"messages[{index}].content must be a string")
        messages.append({
            "role": "user" if role == "developer" else str(role),
            "content": content,
        })

    raw_max_tokens = payload.get("max_tokens")
    if raw_max_tokens is None:
        raw_max_tokens = payload.get("max_completion_tokens")
    if raw_max_tokens is None:
        raw_max_tokens = MAX_TOKENS

    try:
        temperature = float(payload.get("temperature", TEMP))
        top_p = float(payload.get("top_p", TOP_P))
        max_tokens = int(raw_max_tokens)
    except (TypeError, ValueError) as exc:
        raise RequestError("temperature, top_p and max_tokens must be numbers") from exc

    if not 0.0 <= temperature <= 2.0:
        raise RequestError("temperature must be between 0 and 2")
    if not 0.0 < top_p <= 1.0:
        raise RequestError("top_p must be between 0 and 1")
    if max_tokens < 1:
        raise RequestError("max_tokens must be at least 1")

    return {
        "model": str(payload.get("model") or default_model),
        "messages": messages,
        "temperature": temperature,
        "top_p": top_p,
        "max_tokens": min(max_tokens, MAX_MAX_TOKENS),
        "stream": bool(payload.get("stream", False)),
    }


def with_system_prompt(messages: list[dict[str, str]]) -> list[dict[str, str]]:
    """Ensure Pari's identity prompt is present exactly once."""
    if any(message.get("role") == "system" for message in messages):
        return list(messages)
    return [{"role": "system", "content": PARI_SYSTEM_PROMPT}, *messages]


def completion_response(text: str, model: str, prompt_tokens: int = 0) -> dict:
    """Build a non-streaming chat completion body."""
    completion_tokens = max(1, len(text) // 4) if text else 0
    return {
        "id": f"chatcmpl-{uuid.uuid4().hex[:24]}",
        "object": "chat.completion",
        "created": int(time.time()),
        "model": model,
        "choices": [
            {
                "index": 0,
                "message": {"role": "assistant", "content": text},
                "finish_reason": "stop",
            }
        ],
        "usage": {
            "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens,
            "total_tokens": prompt_tokens + completion_tokens,
        },
    }


def sse_event(data: dict | str) -> str:
    """Frame one server-sent event."""
    body = data if isinstance(data, str) else json.dumps(data, ensure_ascii=False)
    return f"data: {body}\n\n"


def sse_delta(text: str, model: str, *, role: str | None = None, finish: bool = False) -> str:
    """Frame one streaming chat.completion.chunk."""
    delta: dict[str, str] = {}
    if role:
        delta["role"] = role
    if text:
        delta["content"] = text
    chunk = {
        "id": f"chatcmpl-{uuid.uuid4().hex[:24]}",
        "object": "chat.completion.chunk",
        "created": int(time.time()),
        "model": model,
        "choices": [{
            "index": 0,
            "delta": delta,
            "finish_reason": "stop" if finish else None,
        }],
    }
    return sse_event(chunk)


def is_authorized(header_value: str | None, api_key: str | None) -> bool:
    """Check a Bearer token when the server was started with one."""
    if not api_key:
        return True
    if not header_value:
        return False
    scheme, _, token = header_value.partition(" ")
    if scheme.lower() != "bearer":
        return False
    return hmac.compare_digest(token.strip(), api_key)


def models_response(model_id: str = DEFAULT_MODEL_ID) -> dict:
    return {
        "object": "list",
        "data": [{
            "id": model_id,
            "object": "model",
            "created": 0,
            "owned_by": MODEL_DISPLAY,
        }],
    }


# ---------------------------------------------------------------------------
# Backends
# ---------------------------------------------------------------------------

class MlxBackend:
    """Runs the local MLX weights. Nothing here talks to a network service."""

    def __init__(self, model_id: str = MODEL, thinking: bool = ENABLE_THINKING):
        self.model_id = model_id
        self.thinking = thinking
        self._model = None
        self._tokenizer = None

    def load(self) -> tuple[Any, Any]:
        if self._model is None:
            from mlx_lm import load

            self._model, self._tokenizer = load(self.model_id)
        return self._model, self._tokenizer

    def stream(
        self,
        messages: list[dict[str, str]],
        temperature: float,
        top_p: float,
        max_tokens: int,
    ) -> Iterator[str]:
        from mlx_lm import stream_generate
        from mlx_lm.generate import make_sampler

        model, tokenizer = self.load()
        prompt = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True,
            enable_thinking=self.thinking,
        )
        sampler = make_sampler(temp=temperature, top_p=top_p)
        for response in stream_generate(
            model,
            tokenizer,
            prompt=prompt,
            max_tokens=max_tokens,
            sampler=sampler,
        ):
            yield response.text


# ---------------------------------------------------------------------------
# HTTP layer
# ---------------------------------------------------------------------------

class PariHandler(BaseHTTPRequestHandler):
    server_version = "Pari/1.0"
    protocol_version = "HTTP/1.1"

    # -- plumbing ---------------------------------------------------------
    @property
    def backend(self) -> Any:
        return getattr(self.server, "backend")

    @property
    def model_id(self) -> str:
        return getattr(self.server, "model_id", DEFAULT_MODEL_ID)

    @property
    def api_key(self) -> str | None:
        return getattr(self.server, "api_key", None)

    def log_message(self, format: str, *args: Any) -> None:  # noqa: A002
        # Quiet by default; chat content must never land in logs.
        if getattr(self.server, "verbose", False):
            super().log_message(format, *args)

    def _cors(self) -> None:
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Headers", "authorization, content-type")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")

    def _send_json(self, status: int, body: dict) -> None:
        data = json.dumps(body, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self._cors()
        self.end_headers()
        self.wfile.write(data)

    def _send_error_json(self, status: int, message: str) -> None:
        self._send_json(status, {"error": {"message": message, "type": "invalid_request_error"}})

    def _read_payload(self) -> Any:
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError as exc:
            raise RequestError("invalid Content-Length") from exc
        if length <= 0:
            raise RequestError("empty request body")
        if length > MAX_REQUEST_BYTES:
            raise RequestError("request body too large")
        raw = self.rfile.read(length)
        try:
            return json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise RequestError("request body must be valid JSON") from exc

    def _authorized(self) -> bool:
        return is_authorized(self.headers.get("Authorization"), self.api_key)

    # -- verbs ------------------------------------------------------------
    def do_OPTIONS(self) -> None:  # noqa: N802
        self.send_response(204)
        self._cors()
        self.send_header("Content-Length", "0")
        self.end_headers()

    def do_GET(self) -> None:  # noqa: N802
        path = self.path.split("?", 1)[0].rstrip("/") or "/"
        if path == "/health":
            self._send_json(200, {
                "status": "ok",
                "model": self.model_id,
                "display": MODEL_DISPLAY,
                "engine": "mlx",
            })
            return
        if path == "/v1/models":
            if not self._authorized():
                self._send_error_json(401, "invalid or missing API key")
                return
            self._send_json(200, models_response(self.model_id))
            return
        self._send_error_json(404, f"unknown path: {path}")

    def do_POST(self) -> None:  # noqa: N802
        path = self.path.split("?", 1)[0].rstrip("/") or "/"
        if path != "/v1/chat/completions":
            self._send_error_json(404, f"unknown path: {path}")
            return
        if not self._authorized():
            self._send_error_json(401, "invalid or missing API key")
            return

        try:
            request = parse_chat_request(self._read_payload(), self.model_id)
        except RequestError as exc:
            self._send_error_json(400, str(exc))
            return

        messages = with_system_prompt(request["messages"])
        kwargs = {
            "messages": messages,
            "temperature": request["temperature"],
            "top_p": request["top_p"],
            "max_tokens": request["max_tokens"],
        }

        if request["stream"]:
            self._stream_completion(kwargs)
            return

        try:
            text = "".join(self.backend.stream(**kwargs))
        except Exception as exc:  # pragma: no cover - model/runtime failure
            self._send_error_json(500, f"generation failed: {exc}")
            return
        self._send_json(200, completion_response(text, request["model"]))

    def _stream_completion(self, kwargs: dict) -> None:
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream; charset=utf-8")
        self.send_header("Cache-Control", "no-cache")
        self.send_header("Connection", "close")
        self._cors()
        self.end_headers()

        try:
            self.wfile.write(sse_delta("", kwargs.get("model", self.model_id), role="assistant").encode())
            for piece in self.backend.stream(**kwargs):
                if piece:
                    self.wfile.write(sse_delta(piece, self.model_id).encode())
                    self.wfile.flush()
            self.wfile.write(sse_delta("", self.model_id, finish=True).encode())
            self.wfile.write(sse_event("[DONE]").encode())
            self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError):
            return
        except Exception as exc:  # pragma: no cover - model/runtime failure
            try:
                self.wfile.write(sse_event({"error": {"message": str(exc)}}).encode())
                self.wfile.flush()
            except OSError:
                pass


def make_server(
    host: str = "127.0.0.1",
    port: int = 8080,
    *,
    backend: Any | None = None,
    api_key: str | None = None,
    model_id: str = DEFAULT_MODEL_ID,
    model: str = MODEL,
    thinking: bool = ENABLE_THINKING,
    verbose: bool = False,
) -> ThreadingHTTPServer:
    server = ThreadingHTTPServer((host, port), PariHandler)
    server.backend = backend if backend is not None else MlxBackend(model, thinking)
    server.api_key = api_key
    server.model_id = model_id
    server.verbose = verbose
    return server


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Serve Pari over local HTTP.")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8080)
    parser.add_argument("--model", default=MODEL, help="weights to load (local path or hub id)")
    parser.add_argument("--model-id", default=DEFAULT_MODEL_ID, help="id clients see in /v1/models")
    parser.add_argument(
        "--api-key",
        default=os.environ.get("PARI_API_KEY") or None,
        help="require this Bearer token (also read from PARI_API_KEY)",
    )
    parser.add_argument("--no-thinking", action="store_true", help="disable chain-of-thought")
    parser.add_argument("--verbose", action="store_true", help="log requests (never logs content)")
    args = parser.parse_args(argv)

    server = make_server(
        args.host,
        args.port,
        api_key=args.api_key,
        model_id=args.model_id,
        model=args.model,
        thinking=not args.no_thinking,
        verbose=args.verbose,
    )
    host, port = server.server_address[:2]
    print(f"{MODEL_DISPLAY} serving on http://{host}:{port}/v1  (model: {args.model})")
    print("Press Ctrl+C to stop.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nstopping")
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
